#!/usr/bin/env python3
"""Assemble a small Pages site from reviewed runtime files, not the whole repo.

Run from any directory. This deliberately excludes raw experiment directories,
Blender files, caches, source archives, and logs from the deployed artifact.
"""
from pathlib import Path
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'dist/site'
MARKER = '.xorex-site-builder'
LFS_POINTER = b'version https://git-lfs.github.com/spec/v1'
RUNTIME_EXTENSIONS = {'.html', '.css', '.js', '.mjs', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.swf', '.mp3', '.md', '.json'}
TREES = ['01-ruffle', '03-svg-demake', '04-rendering-lab', '05-autoplay-lab', '06-autoplay-playable']
EXCLUDED_PARTS = {'generated', '.cache', '__pycache__', 'node_modules', '.venv', '.git', '.openchamber', 'blender'}


def main():
    if OUT.exists():
        if not (OUT / MARKER).is_file():
            raise SystemExit(f'Refusing to replace unrecognized directory {OUT}')
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    (OUT / MARKER).write_text('Generated by tools/build_site.py\n')
    manifest = []

    def copy(relative):
        path = ROOT / relative
        assert not path.is_symlink(), f'Symlink not deployed: {relative}'
        data = path.read_bytes()
        assert not data.startswith(LFS_POINTER), f'Unresolved LFS pointer: {relative}. Run git lfs pull.'
        target = OUT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        manifest.append({'path': str(relative), 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()})

    for path in ['index.html', 'gallery.html', 'README.md', 'RIGHTS.md']:
        copy(Path(path))
    for directory in TREES:
        for path in sorted((ROOT / directory).rglob('*')):
            relative = path.relative_to(ROOT)
            if not path.is_file() or any(part in EXCLUDED_PARTS for part in relative.parts):
                continue
            if path.suffix not in RUNTIME_EXTENSIONS or path.name.endswith('.test.mjs'):
                continue
            copy(relative)
    # Readable source documentation, including lossless-inspection findings.
    for path in ['02-decompilation/MECHANICS.md', '02-decompilation/fidelity-report.json',
                 '02-decompilation/README.md', 'docs/rules/xorex-rules.pdf',
                 'docs/rules/VOCABULARY.md', 'docs/rules/README.md',
                 'docs/rules/BITSTREAM-VERA-LICENSE.txt',
                 'docs/design/pressure-progression.md', 'docs/design/heuristic-learning.md']:
        copy(Path(path))
    # Only these review images are deployed. The rest remain downloadable in Git LFS.
    for path in ['04-rendering-lab/references/original-gameplay.png',
                 '04-rendering-lab/blender/generated/designs-02/reliquary-board.png',
                 '04-rendering-lab/blender/generated/designs-02/pelagic-board.png',
                 '04-rendering-lab/blender/generated/designs-02/archive-board.png',
                 '04-rendering-lab/blender/used-idealism/generated/study-03/board.png']:
        relative = Path(path)
        if not any(item['path'] == str(relative) for item in manifest): copy(relative)
    total = sum(item['bytes'] for item in manifest)
    assert total < 50 * 1024 * 1024, f'Unexpected Pages size: {total:,} bytes'
    (OUT / '.nojekyll').write_text('')
    (OUT / 'site-manifest.json').write_text(json.dumps({'bytes': total, 'files': manifest}, indent=2) + '\n')
    print(f'Pages site: {len(manifest)} files, {total / 1048576:.2f} MiB at {OUT}')


if __name__ == '__main__': main()
