"""Inspect SWF headers and the Haxe initializer FFDec's AS export omits.

This deliberately narrow decoder fails on unknown instructions. It is not an
AVM2 interpreter or a general disassembler. XML input is generated by FFDec.
"""
from pathlib import Path
import hashlib
import json
import struct
import xml.etree.ElementTree as ET
import zlib

HERE = Path(__file__).resolve().parent


def header(path):
    raw = path.read_bytes()
    data = zlib.decompress(raw[8:]) if raw[:3] == b"CWS" else raw[8:]
    rect_bytes = (5 + 4 * (data[0] >> 3) + 7) // 8
    fps, frames = struct.unpack_from("<HH", data, rect_bytes)
    pos = rect_bytes + 4
    background = None
    while pos < len(data):
        tag = int.from_bytes(data[pos:pos + 2], "little")
        pos += 2
        kind, length = tag >> 6, tag & 63
        if length == 63:
            length = int.from_bytes(data[pos:pos + 4], "little")
            pos += 4
        if kind == 9:
            background = "#" + data[pos:pos + length].hex()
        pos += length
        if kind == 0:
            break
    return {"file": str(path.relative_to(HERE.parent)), "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(), "swf_version": raw[3],
            "fps": fps / 256, "frames": frames, "background": background}


def initializer():
    abc = ET.parse(HERE / "generated/xorex.xml").getroot().find(".//abc")
    constants = abc.find("constants")
    strings = [x.text or "" for x in constants.find("constant_string")]
    names = [strings[int(x.get("name_index", "0"))]
             for x in constants.find("constant_multiname")]
    body = next(x for x in abc.find("bodies") if x.get("method_info") == "315")
    code = bytes.fromhex(body.get("codeBytes"))
    pos = 0

    def u30():
        nonlocal pos
        value = 0
        for shift in range(0, 35, 7):
            byte = code[pos]
            pos += 1
            value |= (byte & 127) << shift
            if byte < 128:
                return value
        raise ValueError("invalid U30")

    single = {0x82: "coerce_a", 0x75: "convert_i", 0x64: "getglobalscope",
              0xd5: "setlocal1", 0xd1: "getlocal1", 0x27: "pushfalse",
              0x26: "pushtrue", 0x47: "returnvoid"}
    multiname = {0x60: "getlex", 0x66: "getproperty", 0x68: "initproperty", 0x61: "setproperty"}
    rows = []
    while pos < len(code):
        offset = pos
        op = code[pos]
        pos += 1
        if op in single:
            text = single[op]
        elif op in multiname:
            text = f"{multiname[op]} {names[u30()]}"
        elif op == 0x24:
            n = code[pos]
            pos += 1
            text = f"pushbyte {n if n < 128 else n - 256}"
        elif op in (0x40, 0x6d, 0x56):
            text = f"{ {0x40: 'newfunction', 0x6d: 'setslot', 0x56: 'newarray'}[op]} {u30()}"
        elif op == 0x46:
            text = f"callproperty {names[u30()]} argc={u30()}"
        elif op == 0x80:
            text = f"coerce {names[u30()]}"
        else:
            raise ValueError(f"unknown opcode {op:02x} at {offset:04x}")
        rows.append(f"{offset:04x} {text}")
    return "\n".join(rows) + "\n"


if __name__ == "__main__":
    print(json.dumps(header(HERE.parent / "01-ruffle/Xorex.swf"), indent=2))
    output = initializer()
    (HERE / "generated/initializer.txt").write_text(output)
    print(output)
